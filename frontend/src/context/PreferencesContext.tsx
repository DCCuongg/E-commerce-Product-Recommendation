function initialLanguage(): Language { try {return localStorage.getItem(LANGUAGE_KEY) === 'vi' ? 'vi' : 'en';} catch{return 'en';} }
function initialTheme(): Theme {
  try { const stored = localStorage.getItem(THEME_KEY); if(stored==='dark'||stored==='light') return stored; } catch {/* unavailable */}
  return typeof window !== 'undefined' && window.matchMedia?.('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
}
function interpolate(input: string, vars?: Record<string,string|number>): string {
  if(!vars) return input;
  return input.replace(/\{(\w+)\}/g,(_match,key:string)=>String(vars[key]??''));
}
