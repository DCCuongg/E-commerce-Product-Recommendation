# 2. Ping bất đồng bộ kiểm tra link ảnh sống
async def check_url_alive(session: aiohttp.ClientSession, url: str, sem: asyncio.Semaphore) -> bool:
    if not url or not url.startswith(("http://", "https://")):
        return False
    async with sem:
        try:
            async with session.head(url, headers=HEADERS, timeout=aiohttp.ClientTimeout(total=5), allow_redirects=True) as resp:
                if resp.status == 200 and "image" in resp.headers.get("Content-Type", "").lower():
                    return True
                if resp.status in (403, 405):
                    async with session.get(url, headers=HEADERS, timeout=aiohttp.ClientTimeout(total=5), allow_redirects=True) as get_resp:
                        return get_resp.status == 200 and "image" in get_resp.headers.get("Content-Type", "").lower()
            return False
        except Exception:
            return False

async def validate_all_candidates():
    urls_to_check = set()
    candidates_by_pid = {}

    for _, row in df_train_old.iterrows():
        pid = str(row["product_id"])
        old_url = str(row.get("thumbnail_url") or row.get("image_url") or "")
        imgs = matched_images_meta.get(pid, {"hi_res": [], "large": [], "thumb": []})

        hi_cands = imgs["hi_res"][:3]
        lg_cands = imgs["large"][:5]
        th_cands = imgs["thumb"][:3]

        if old_url.startswith("http"):
            if not lg_cands:
                lg_cands.append(old_url)
            if not th_cands:
                th_cands.append(old_url)

        candidates_by_pid[pid] = {"hi_res": hi_cands, "large": lg_cands, "thumb": th_cands}
        urls_to_check.update(hi_cands + lg_cands + th_cands)

    print(f"🌐 [2/2] Đang ping kiểm tra sống {len(urls_to_check)} URL ảnh ứng viên...")
    url_list = list(urls_to_check)
    sem = asyncio.Semaphore(80)
    connector = aiohttp.TCPConnector(limit=80, ssl=False)
    async with aiohttp.ClientSession(connector=connector) as session:
        flags = await asyncio.gather(*(check_url_alive(session, u, sem) for u in url_list))
    alive_map = dict(zip(url_list, flags))

    resolved = {}
    for pid, cands in candidates_by_pid.items():
        live_large = [u for u in cands["large"] if alive_map.get(u)][:3]
        live_hi = next((u for u in cands["hi_res"] if alive_map.get(u)), None)
        live_thumb = next((u for u in cands["thumb"] if alive_map.get(u)), None)

        fallback = live_large[0] if live_large else (live_hi or live_thumb or "")
        if not live_hi:
            live_hi = fallback
        if not live_large and fallback:
            live_large = [fallback]
        if not live_thumb:
            live_thumb = fallback

        resolved[pid] = {
            "hi_res_url": live_hi,
            "large_urls": live_large,
            "thumb_url": live_thumb,
        }
    return resolved

loop = asyncio.get_event_loop()
source_images_map = loop.run_until_complete(validate_all_candidates())

