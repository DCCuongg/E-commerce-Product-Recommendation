def clean_url_list(raw_list) -> list:
    if raw_list is None:
        return []
    if hasattr(raw_list, "tolist"):
        raw_list = raw_list.tolist()
    if not isinstance(raw_list, (list, tuple)):
        raw_list = [raw_list]
    seen = set()
    result = []
    for u in raw_list:
        if isinstance(u, str):
            u_clean = u.strip()
            if u_clean.startswith(("http://", "https://")) and u_clean not in seen:
                seen.add(u_clean)
                result.append(u_clean)
    return result

def extract_image_candidates(images_field) -> dict:
    hi_res, large, thumb = [], [], []
    if isinstance(images_field, dict):
        hi_res = clean_url_list(images_field.get("hi_res"))
        large = clean_url_list(images_field.get("large"))
        thumb = clean_url_list(images_field.get("thumb"))
    elif isinstance(images_field, (list, tuple)):
        for entry in images_field:
            if isinstance(entry, dict):
                hi_res.extend(clean_url_list(entry.get("hi_res")))
                large.extend(clean_url_list(entry.get("large")))
                thumb.extend(clean_url_list(entry.get("thumb")))
            elif isinstance(entry, str):
                large.extend(clean_url_list(entry))
    return {
        "hi_res": clean_url_list(hi_res),
        "large": clean_url_list(large),
        "thumb": clean_url_list(thumb),
    }

